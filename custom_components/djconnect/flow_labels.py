def flow_label(hass: Any, key: str) -> str:
    """Resolve a stable label key with regional normalization and English fallback."""
    language = str(getattr(getattr(hass, "config", None), "language", "") or "")
    family = language.lower().replace("_", "-").split("-", 1)[0]
    return LABELS.get(family, LABELS["en"])[key]
