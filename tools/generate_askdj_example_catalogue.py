"""Generate the import-safe Python projection of the one canonical JSON file."""
import argparse
import hashlib
import json
from pathlib import Path
import pprint

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'custom_components/djconnect/ask_dj/examples_v1.json'
TARGET = SOURCE.with_name('example_catalogue_data.py')


def projection(source):
    return ('# Generated by tools/generate_askdj_example_catalogue.py; do not edit.\n'
        '# Canonical source: ask_dj/examples_v1.json. No runtime file I/O.\n'
        + 'SOURCE_SHA256 = ' + repr(hashlib.sha256(source).hexdigest()) + '\n'
        + 'CATALOGUE = ' + pprint.pformat(json.loads(source), width=100, sort_dicts=False) + '\n')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    expected = projection(SOURCE.read_bytes())
    if args.check:
        if not TARGET.is_file() or TARGET.read_text() != expected:
            raise SystemExit('ask_dj_catalogue_projection_stale')
    else:
        TARGET.write_text(expected)


if __name__ == '__main__':
    main()
