"""Deterministic shared VibeCast builds. No network, provider or deployment effects."""

from __future__ import annotations

import argparse
import hashlib
from html.parser import HTMLParser
import json
import re
from pathlib import Path
import subprocess

SOURCES = ("template.html", "style.css", "renderer.js", "local-host.js", "cast-host.js")
VERSION = "1.1.0"


class InlineScripts(HTMLParser):
    """Extract generated inline scripts; authenticity comes from the pinned digest."""

    def __init__(self):
        super().__init__(convert_charrefs=False)
        self.scripts = []
        self.current = None

    def handle_starttag(self, tag, attrs):
        if tag == "script" and not any(name == "src" for name, _ in attrs):
            self.current = []

    def handle_data(self, data):
        if self.current is not None:
            self.current.append(data)

    def handle_endtag(self, tag):
        if tag == "script" and self.current is not None:
            self.scripts.append("".join(self.current))
            self.current = None


def digest(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def render(root: Path, host: str) -> str:
    source = root / "custom_components/djconnect/vibecast_renderer"
    text = (source / "template.html").read_text()
    text = text.replace("@@STYLE@@", (source / "style.css").read_text())
    renderer = (source / "renderer.js").read_text()
    if host == "cast":
        renderer = 'window.DJC_VIBECAST_MODE = "cast";\n' + renderer
        text = text.replace(
            "<script>@@RENDERER@@",
            '<script src="https://www.gstatic.com/cast/sdk/libs/caf_receiver/v3/cast_receiver_framework.js"></script>\n<script>@@RENDERER@@',
        )
        # CAF requires a media element; this host never loads or plays music/audio.
        text = text.replace("<main>", '<video class="castMediaElement" hidden></video><main>')
    text = text.replace("@@RENDERER@@", renderer)
    text = text.replace("@@HOST@@", (source / (host + "-host.js")).read_text())
    return (
        "<!-- Generated by scripts/build_vibecast.py; edit vibecast_renderer sources only. -->\n"
        + text
    )


def build(root: Path, output: Path, *, source_revision: str) -> dict:
    source = root / "custom_components/djconnect/vibecast_renderer"
    hashes = {name: digest((source / name).read_bytes()) for name in SOURCES}
    files = {}
    for host, name in [("local", "vibecast.html"), ("cast", "index.html")]:
        path = output / host / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(render(root, host), encoding="utf-8")
        files[str(path.relative_to(output))] = digest(path.read_bytes())
    manifest = {
        "schema_version": 1,
        "build_version": VERSION,
        "source_revision": source_revision,
        "renderer_source_sha256": hashes["renderer.js"],
        "sources": hashes,
        "contracts": {
            "cast_handoff_versions": [1],
            "cast_status_versions": [1],
            "broadcast_transport": "snapshot-event-v1",
            "required_capabilities": {"view_broadcast": True, "owner_controls": False},
        },
        "files": files,
        "private_runtime_data_in_build": False,
        "promotion": "explicit receiver-owner import; no automatic deployment",
    }
    output.mkdir(parents=True, exist_ok=True)
    (output / "manifest.json").write_text(json.dumps(manifest, sort_keys=True, indent=2) + "\n")
    return manifest


def verify(
    output: Path,
    *,
    expected_manifest_sha256: str | None = None,
    expected_revision: str | None = None,
) -> list[str]:
    try:
        raw = (output / "manifest.json").read_bytes()
        manifest = json.loads(raw)
        if expected_manifest_sha256 is not None and digest(raw) != expected_manifest_sha256:
            return ["untrusted_manifest_digest"]
        if expected_revision is not None and manifest.get("source_revision") != expected_revision:
            return ["wrong_source_revision"]
        expected_keys = {
            "schema_version",
            "build_version",
            "source_revision",
            "renderer_source_sha256",
            "sources",
            "contracts",
            "files",
            "private_runtime_data_in_build",
            "promotion",
        }
        if (
            set(manifest) != expected_keys
            or type(manifest["schema_version"]) is not int
            or manifest["schema_version"] != 1
        ):
            return ["invalid_manifest"]
        if manifest["build_version"] != VERSION or not re.fullmatch(
            r"[0-9a-f]{40}", manifest["source_revision"]
        ):
            return ["invalid_build_identity"]
        if set(manifest["sources"]) != set(SOURCES) or any(
            not re.fullmatch(r"[0-9a-f]{64}", value) for value in manifest["sources"].values()
        ):
            return ["invalid_source_hashes"]
        if manifest["renderer_source_sha256"] != manifest["sources"]["renderer.js"]:
            return ["inconsistent_renderer_identity"]
        if (
            manifest["contracts"]
            != {
                "cast_handoff_versions": [1],
                "cast_status_versions": [1],
                "broadcast_transport": "snapshot-event-v1",
                "required_capabilities": {"view_broadcast": True, "owner_controls": False},
            }
            or manifest["private_runtime_data_in_build"] is not False
        ):
            return ["unsupported_contract"]
        if set(manifest["files"]) != {"local/vibecast.html", "cast/index.html"} or any(
            not re.fullmatch(r"[0-9a-f]{64}", value) for value in manifest["files"].values()
        ):
            return ["invalid_asset_manifest"]
        errors = []
        for name, expected in manifest["files"].items():
            path = output / name
            if path.is_symlink() or not path.is_file() or digest(path.read_bytes()) != expected:
                errors.append("missing_or_changed_asset:" + name)
            else:
                parser = InlineScripts()
                parser.feed(path.read_text())
                script = parser.scripts[0]
                if name.startswith("cast/"):
                    script = script.removeprefix('window.DJC_VIBECAST_MODE = "cast";\n')
                if digest(script.encode()) != manifest["renderer_source_sha256"]:
                    errors.append("renderer_source_mismatch:" + name)
        actual = {str(p.relative_to(output)) for p in output.rglob("*") if p.is_file()}
        if actual != set(manifest["files"]) | {"manifest.json"}:
            errors.append("unexpected_assets")
        return errors
    except (OSError, ValueError, KeyError, TypeError, IndexError):
        return ["invalid_manifest"]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--revision")
    parser.add_argument("--check-local", action="store_true")
    parser.add_argument("--write-local", action="store_true")
    parser.add_argument("--verify-existing", action="store_true")
    parser.add_argument("--expected-manifest-sha256")
    args = parser.parse_args()
    if args.verify_existing:
        if not args.expected_manifest_sha256 or not args.revision:
            raise SystemExit("Pinned import requires expected manifest SHA256 and exact revision")
        errors = verify(
            args.output,
            expected_manifest_sha256=args.expected_manifest_sha256,
            expected_revision=args.revision,
        )
        if errors:
            raise SystemExit(",".join(errors))
        print("Pinned manifest and asset verification PASS")
        return
    root = Path(__file__).resolve().parents[1]
    revision = (
        args.revision
        or subprocess.check_output(["git", "rev-parse", "HEAD"], cwd=root, text=True).strip()
    )
    build(root, args.output, source_revision=revision)
    local = root / "custom_components/djconnect/vibecast.html"
    if args.write_local:
        local.write_text(render(root, "local"))
    if args.check_local and local.read_text() != render(root, "local"):
        raise SystemExit("Generated local VibeCast drift: run --write-local")
    errors = verify(args.output)
    if errors:
        raise SystemExit(",".join(errors))
    print(json.dumps({"build_version": VERSION, "revision": revision, "verification": "PASS"}))


if __name__ == "__main__":
    main()
